"""Interfaces / ports: other layers implement these contracts."""
from typing import Protocol, Optional
from ..domain.models import Prediction, Attempt

class VoicePort(Protocol):
    def say_letter(self, letter: str) -> None: ...

class CameraPort(Protocol):
    def open(self): ...
    def read(self): ...
    def close(self): ...

class ImageModelPort(Protocol):
    def predict(self, image) -> Optional[Prediction]: ...

class SpeechModelPort(Protocol):
    def recognize_letter(self, audio) -> Optional[Prediction]: ...

class ProgressPort(Protocol):
    def save(self, attempt: Attempt): ...
    def summary(self) -> dict: ...
    def recent(self, limit: int = 8) -> list: ...
